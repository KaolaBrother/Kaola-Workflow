# Report the project declaration carrier after every project install. This is
# diagnostic only: ZCode owns trust, the generator owns declarations, and the
# receipt owns cleanup.
report_hook_diagnostics() {
  [[ "$GLOBAL" -eq 0 ]] || return 0
  local config_file="$LAYOUT_DEST/config.json"
  [[ -f "$config_file" ]] || return 0
  ZCODE_HOOK_CONFIG="$config_file" node <<'NODE'
const fs = require('fs');
const file = process.env.ZCODE_HOOK_CONFIG;
try {
  const config = JSON.parse(fs.readFileSync(file, 'utf8'));
  const events = config && config.hooks && config.hooks.events;
  const names = events && typeof events === 'object' && !Array.isArray(events)
    ? Object.keys(events) : [];
  let matcherRows = 0;
  let hookCount = 0;
  let invalidRows = 0;
  for (const name of names) {
    const rows = Array.isArray(events[name]) ? events[name] : [];
    matcherRows += rows.length;
    for (const row of rows) {
      if (!row || typeof row !== 'object' || !Array.isArray(row.hooks)) {
        invalidRows++;
        continue;
      }
      hookCount += row.hooks.length;
    }
  }
  console.log('ZCode 3.10.1 config=' + file + ' events=' + names.join(',')
    + ' matcherRows=' + matcherRows + ' hookCount=' + hookCount
    + ' invalidRows=' + invalidRows);
  if (invalidRows > 0) process.exitCode = 1;
} catch (error) {
  console.error('ZCode 3.10.1 config diagnostics unavailable: ' + error.message);
  process.exitCode = 1;
}
NODE
}

report_hook_diagnostics

echo ""
echo "Next: open the project in ZCode and run /workflow-init or /workflow-next."
