#!/usr/bin/env bash
# install-hermes.sh — deploy the Kaola-Workflow Hermes Agent edition.
#
# Hermes Agent is a coding-agent RUNTIME, not a git forge. It is delivered the
# Hermes-native way: skills under $HERMES_HOME/skills/<name>/SKILL.md plus a
# managed machine-global contract region in $HERMES_HOME/SOUL.md. This runtime
# installs no Kaola role profiles, NO hooks, and NO Hermes plugin by design.
#
# D1/D2/D4/D5 (#1124): KW delivers natively; the global carrier is the SOUL.md
# managed region (G-a); P1 installs global scope only; the repo-side build tree is
# `.kw-hermes[-<forge>]/`, never `<repo>/.hermes/`.
#
# FORGE: --forge=github|gitlab|gitea selects which forge's workflow prose and
# support scripts to deploy (default github). The forge variants are GENERATED by
# sync-hermes-edition.js from the same routing surfaces the other editions ship.
#
# Usage:
#   ./install-hermes.sh                       # global install into ${HERMES_HOME:-~/.hermes}
#   ./install-hermes.sh --global              # same as above (the only supported scope)
#   ./install-hermes.sh --check               # verify installed artifacts
#   ./install-hermes.sh --uninstall           # remove only Kaola-deployed artifacts
#   ./install-hermes.sh --forge=gitlab        # deploy GitLab-shaped workflow prose
#
# Global layout:
#   $HERMES_HOME/skills/<name>/SKILL.md
#   $HERMES_HOME/SOUL.md   (managed global contract, via kaola-workflow-global-contract.js —
#                           per-target: --runtime hermes installs/checks ONLY this runtime's own
#                           carrier, as the LAST install step; no other runtime's home is written)
#   $HERMES_HOME/kaola-workflow/scripts  (support scripts)
#
# Hermes reads HERMES_HOME for its profile home (measured; P0 M9). This installer
# never writes config.yaml, .env, credentials, hooks, or any Hermes plugin surface.
#
# Project scope is deliberately not implemented in P1 (D4): Hermes project skills
# require the owner to trust the root in config.yaml's skills.trusted_project_dirs,
# and this installer never writes the owner's config. --project/--target is
# refused rather than silently redirected to a global install.
#
# Uninstall: --uninstall removes ONLY Kaola-deployed artifacts — the skills by rendered
# directory name (never a blind rm of the skills dir), the support scripts by manifest
# name, and this runtime's OWN managed region in SOUL.md through its own per-target
# global-contract record (an owner-edited carrier is refused and left in place).

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
FORGE="github"
CHECK=0
UNINSTALL=0
YES=0

usage() {
  cat <<'EOF'
Usage: ./install-hermes.sh [--global] [--forge=github|gitlab|gitea] [--check] [--uninstall] [-y|--yes]
  --global          install global skills into ${HERMES_HOME:-~/.hermes} (default)
  --forge F         github (default), gitlab, or gitea
  --check           verify installed artifacts without mutating
  --uninstall       remove only Kaola-deployed skills, support scripts, and this runtime's
                    own global-contract region in SOUL.md, then exit
  -y, --yes         non-interactive (ignored; accepted for install-all compatibility)
  -h, --help        show this help

Hermes is global-only in Kaola-Workflow P1 (D4, #1124): project scope requires the
owner to trust the repository in Hermes' skills.trusted_project_dirs, and this
installer never writes the owner's config. --project/--target is refused.

Uninstall removes ONLY Kaola-deployed artifacts: the deployed skills (by source-tree
directory name — never a blind rm of a dir), the support scripts (by manifest name),
and this runtime's own managed region in SOUL.md through its per-target global-contract
record (an owner-edited carrier is refused and left in place). This installer never
writes config.yaml, .env, credentials, hooks, or a Hermes plugin.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --forge=*) FORGE="${1#*=}"; shift ;;
    --forge) FORGE="${2:?--forge requires github, gitlab, or gitea}"; shift 2 ;;
    --global) shift ;;
    --project|--project=*|--target|--target=*)
      echo "install-hermes.sh: project scope is not supported (D4, #1124 P1); use --global." >&2
      exit 2 ;;
    --check) CHECK=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    -y|--yes) YES=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ -n "${HERMES_HOME:-}" ]]; then
  HOME_ROOT="$HERMES_HOME"
else
  # M9: do not guess a home when a non-default profile is sticky-active. Hermes
  # itself warns about this fallback; the installer refuses instead.
  HOME_ROOT="${HOME:?}/.hermes"
  if [[ -f "${HOME}/.hermes/active_profile" ]]; then
    ACTIVE_PROFILE="$(tr -d '[:space:]' < "${HOME}/.hermes/active_profile")"
    if [[ -n "$ACTIVE_PROFILE" && "$ACTIVE_PROFILE" != "default" ]]; then
      echo "Install error: HERMES_HOME is unset but active profile is '$ACTIVE_PROFILE'; set HERMES_HOME explicitly." >&2
      exit 2
    fi
  fi
fi
case "$HOME_ROOT" in
  /*) ;;
  *) echo "Install error: HERMES_HOME must be an absolute path: $HOME_ROOT" >&2; exit 2 ;;
esac

STAGE="$(mktemp -d "${TMPDIR:-/tmp}/kw-hermes-install.XXXXXX")"
cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT

echo "Kaola-Workflow · hermes edition ($FORGE) — staging generated artifacts..."
node "$SCRIPT_DIR/scripts/sync-hermes-edition.js" --forge="$FORGE" --tree-root="$STAGE" --write

FORGE_HELPER="$SCRIPT_DIR/scripts/runtime-edition-forge.js"
if [[ ! -f "$FORGE_HELPER" ]]; then
  echo "Install error: forge layout helper missing: $FORGE_HELPER" >&2
  exit 1
fi
if ! FORGE_SUFFIX="$(node "$FORGE_HELPER" --forge="$FORGE" --out-suffix)"; then
  echo "Install error: unknown forge \"$FORGE\" (expected github, gitlab, or gitea)" >&2
  exit 2
fi
if ! FORGE_SCRIPTS_DIR="$(node "$FORGE_HELPER" --forge="$FORGE" --scripts-dir)"; then
  echo "Install error: cannot resolve the support-script dir for forge $FORGE" >&2
  exit 1
fi

SOURCE_TREE="$STAGE/.kw-hermes$FORGE_SUFFIX"
SUPPORT_DEST="$HOME_ROOT/kaola-workflow/scripts"
SKILLS_DEST="$HOME_ROOT/skills"
SUPPORT_MANIFEST=()
while IFS= read -r line; do [[ -n "$line" ]] && SUPPORT_MANIFEST+=("$line"); done \
  < <(node "$SCRIPT_DIR/scripts/kaola-workflow-install-manifest.js" --forge="$FORGE" --scripts)

# Refuse a symlinked carrier or destination before the first write. The global
# contract also refuses SOUL.md symlinks; this catches the whole install early.
preflight_symlinks() {
  local path
  for path in "$HOME_ROOT/SOUL.md" "$SKILLS_DEST" "$SUPPORT_DEST"; do
    if [[ -L "$path" ]]; then
      echo "Install error: refusing to write through symlink: $path" >&2
      exit 2
    fi
  done
}

# Install or check the managed SOUL.md carrier through the per-target
# global-contract CLI (#1087): --runtime hermes selects ONLY the hermes-local target,
# so another runtime's carrier conflict or drift can never fail this installer.
global_contract() {
  local mode="$1" output rc=0
  output="$(node "$SCRIPT_DIR/scripts/kaola-workflow-global-contract.js" "$mode" --runtime hermes --json 2>&1)" || rc=$?
  node - "$mode" "$rc" "$HOME_ROOT/SOUL.md" "$output" <<'NODE'
const [mode, rcText, carrierPath, output] = process.argv.slice(2);
const rc = Number(rcText);
let doc = null;
try { doc = JSON.parse(output); } catch (_) { /* non-JSON output is reported verbatim below */ }
const target = doc && Array.isArray(doc.targets) ? doc.targets.find(t => t.id === 'hermes-local') : null;
const overall = doc && doc.status ? doc.status : 'UNKNOWN';
const hermes = target ? target.status : 'ABSENT';
if (rc === 0) process.exit(0);
console.error(`${mode}: hermes global contract ${overall} (exit ${rc}); hermes-local carrier ${hermes} at ${carrierPath}`);
if (!doc) console.error(output);
else if (doc.error) console.error(`${mode}: ${doc.error}`);
if (mode === 'check') console.error('check: run ./install-hermes.sh to refresh the hermes global contract carrier');
process.exit(1);
NODE
}

install_global_carrier() { global_contract install; }
check_global_carrier() { global_contract check; }

install_support_scripts() {
  mkdir -p "$SUPPORT_DEST"
  local src name
  for name in "${SUPPORT_MANIFEST[@]}"; do
    src="$FORGE_SCRIPTS_DIR/$name"
    [[ -f "$src" ]] || { echo "Install error: support script missing: $src" >&2; exit 1; }
    cp "$src" "$SUPPORT_DEST/$name"
  done
}

check_support_scripts() {
  local bad=0 src name
  if [[ ! -d "$SUPPORT_DEST" ]]; then
    echo "check: missing $SUPPORT_DEST" >&2; return 1
  fi
  for name in "${SUPPORT_MANIFEST[@]}"; do
    src="$FORGE_SCRIPTS_DIR/$name"
    if [[ ! -f "$SUPPORT_DEST/$name" ]]; then
      echo "check: missing support script $name" >&2; bad=1
    elif ! diff -q "$src" "$SUPPORT_DEST/$name" >/dev/null 2>&1; then
      echo "check: support script $name drifted from canonical" >&2; bad=1
    fi
  done
  return "$bad"
}

# Verify the Kaola-owned skills match the rendered source, per skill. Unrelated
# user skills in the destination are allowed and never drift-fail the check; a
# missing or drifted KW skill does.
check_artifacts() {
  local src_skills="$SOURCE_TREE/skills"
  local bad=0 src name
  if [[ ! -d "$SKILLS_DEST" || ! -d "$src_skills" ]]; then
    echo "check: missing $SKILLS_DEST" >&2; bad=1
  else
    for src in "$src_skills/"*; do
      [[ -d "$src" ]] || continue
      name="$(basename "$src")"
      if [[ ! -f "$SKILLS_DEST/$name/SKILL.md" ]]; then
        echo "check: missing skill $name" >&2; bad=1
      elif ! diff -q "$src/SKILL.md" "$SKILLS_DEST/$name/SKILL.md" >/dev/null 2>&1; then
        echo "check: skill $name drifted from rendered source" >&2; bad=1
      fi
    done
  fi
  return "$bad"
}

uninstall_global_carrier() {
  local output rc=0 status
  output="$(node "$SCRIPT_DIR/scripts/kaola-workflow-global-contract.js" uninstall --runtime hermes --json 2>&1)" || rc=$?
  status="$(node -e 'try { console.log(JSON.parse(process.argv[1]).status || "UNKNOWN"); } catch (_) { console.log("UNKNOWN"); }' "$output")"
  if [[ "$rc" -eq 0 ]]; then
    echo "hermes global contract carrier: $status"
  else
    echo "warning: hermes global contract carrier left in place ($status, exit $rc)" >&2
    printf '%s\n' "$output" >&2
  fi
}

uninstall_edition() {
  local bad=0 name
  preflight_symlinks
  if [[ -d "$SKILLS_DEST" ]]; then
    for name in $(cd "$SOURCE_TREE/skills" 2>/dev/null && printf '%s\n' */ 2>/dev/null | sed 's#/##' || true); do
      [[ -n "$name" ]] || continue
      if [[ -d "$SKILLS_DEST/$name" ]]; then
        rm -rf "$SKILLS_DEST/$name"
        echo "Removed skill: $SKILLS_DEST/$name"
      fi
    done
    rmdir "$SKILLS_DEST" 2>/dev/null || true
  fi
  if [[ -d "$SUPPORT_DEST" ]]; then
    for name in "${SUPPORT_MANIFEST[@]}"; do
      if [[ -f "$SUPPORT_DEST/$name" ]]; then
        rm -f "$SUPPORT_DEST/$name"
        echo "Removed support script: $SUPPORT_DEST/$name"
      fi
    done
    rmdir "$SUPPORT_DEST" 2>/dev/null || true
    rmdir "$(dirname "$SUPPORT_DEST")" 2>/dev/null || true
  fi
  uninstall_global_carrier
  echo "Hermes edition uninstalled."
  return "$bad"
}

if [[ "$CHECK" == 1 ]]; then
  check_global_carrier
  check_support_scripts || exit 1
  check_artifacts || exit 1
  echo "Hermes edition check passed."
  exit 0
fi

if [[ "$UNINSTALL" == 1 ]]; then
  uninstall_edition
  exit 0
fi

preflight_symlinks
install_support_scripts

mkdir -p "$SKILLS_DEST"
if [[ -d "$SOURCE_TREE/skills" ]]; then
  for src in "$SOURCE_TREE/skills/"*; do
    [[ -d "$src" ]] || continue
    name="$(basename "$src")"
    mkdir -p "$SKILLS_DEST/$name"
    cp "$src/SKILL.md" "$SKILLS_DEST/$name/SKILL.md"
  done
fi

# Last step (#1087): this runtime's own global-contract carrier.
install_global_carrier

echo "Installed Hermes edition ($FORGE) — skills: $SKILLS_DEST, support scripts: $SUPPORT_DEST, global carrier: $HOME_ROOT/SOUL.md"
